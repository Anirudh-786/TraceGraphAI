export function getServiceIcon(serviceName: string = ""): ReactElement {
  const name = String(serviceName).toLowerCase();
  if (name.includes("db") || name.includes("database") || name.includes("sql") || name.includes("store") || name.includes("repo") || name.includes("falkor")) {
    return <IconDatabase size={15} />;
  }
  if (name.includes("pay") || name.includes("bill") || name.includes("checkout") || name.includes("invoice") || name.includes("order")) {
    return <IconCreditCard size={15} />;
  }
  if (name.includes("auth") || name.includes("user") || name.includes("identity") || name.includes("login") || name.includes("security")) {
    return <IconShield size={15} />;
  }
  if (name.includes("gateway") || name.includes("api") || name.includes("web") || name.includes("router") || name.includes("ingress") || name.includes("frontend")) {
    return <IconGlobe size={15} />;
  }
  if (name.includes("queue") || name.includes("kafka") || name.includes("stream") || name.includes("event") || name.includes("broker")) {
    return <IconLayers size={15} />;
  }
  return <IconServer size={15} />;
}
